#!/usr/bin/env python3
# ruff: noqa: RUF001
"""Generate the chess cheat sheets from the live catalogue (never hand-edited).

    uv run python scripts/gen_chess_docs.py

Writes docs/chess/COMMANDS.md (spoken commands, from Appendix A as implemented
in src/games/chess/commands.py) and docs/chess/KEYBOARD.md.
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from games.chess import commands  # noqa: E402
from games.chess.shortcuts import NOTE, SHORTCUTS  # noqa: E402
from games.chess.templates import NATO_LEGEND  # noqa: E402

TITLES = {
    "stop": "Stop (always wins, even mid-sentence)",
    "takeover": "Take-over and spectator",
    "ctl": "Spectator / review controls",
    "game": "Game management",
    "exit": "Pause and exit",
    "review": "Review",
    "answer": "Answers",
    "analysis": "Ask for analysis (once, unless you say “keep …”)",
    "info": "Board questions",
    "settings": "Voice settings",
}
ORDER = [
    "stop",
    "takeover",
    "ctl",
    "game",
    "exit",
    "review",
    "analysis",
    "info",
    "settings",
]

MOVES = """\
## Moves (say any of these; legality decides, ambiguity asks)

| You say | Meaning |
|---|---|
| `e4`, `echo four`, `play e4` | pawn to e4 |
| `pawn to e4`, `e2 to e4`, `from e2 to e4` | pawn e2–e4 |
| `knight to f three`, `horse f3`, `Nf3`, `N f three` | knight to f3 |
| `the knight on g1 to f3`, `my king's knight to f3`, `knight g1 f3` | the g1 knight |
| `the left rook to d1`, `light-squared bishop to b5` | piece by side / colour |
| `bishop takes c6`, `Bxc6`, `knight takes the pawn on e5`, `takes c6` | captures |
| `e takes d5`, `exd5`, `e pawn takes d pawn` | pawn captures |
| `en passant`, `take it en passant` | en passant |
| `take it`, `recapture`, `take back` (recapture), `trade`, `take the free pawn` | context captures |
| `castle`, `castle kingside`, `castle long`, `O-O`, `oh oh oh`, `king to g1` | castling |
| `e8 queen`, `pawn to e8 promote to a knight`, `promote`, `under-promote to rook` | promotion (queen by default) |
| `push e4`, `e pawn up two`, `push the d pawn two`, `pawn forward` | pushes |
| `bishop back`, `retreat the knight` | retreats |
| `one`, `two`, `the left one`, `the one on b1`, `never mind` | answers to “which one?” |

Fillers are ignored anywhere: *please, could you, let's, I'll, um, sir, Jarvis, thanks…*.
Say “knight f3, Jarvis” freely, but **“Hey Jarvis …” at the start belongs to Jarvis** and pauses chess.
Squares by NATO name: alpha bravo charlie delta echo foxtrot golf hotel.
"""


def build_commands() -> str:
    groups: dict[str, dict[str, list[str]]] = defaultdict(lambda: defaultdict(list))
    for rule in commands.RULES:
        for phrase in sorted(rule.phrases):
            groups[rule.group][rule.name].append(phrase)
    out = [
        "# Jarvis Chess — spoken commands",
        "",
        "_Generated by `scripts/gen_chess_docs.py` from the live catalogue._",
        "",
    ]
    out.append(
        "Nothing is analysed, commented on or explained unless you ask. Say **stop** and it all stops."
    )
    out.append("")
    out.append(MOVES)
    stops = sorted(commands.STOP_PHRASES)
    out += ["## Stop", "", "Global: " + " · ".join(f"“{p}”" for p in stops), ""]
    out.append(
        "Narrow: "
        + " · ".join(f"“{p}”" for r in commands.NARROW_STOPS for p in sorted(r.phrases))
    )
    out.append("")
    for g in ORDER:
        if g not in groups or g == "stop":
            continue
        out += [f"## {TITLES.get(g, g.title())}", ""]
        for name, phrases in groups[g].items():
            shown = phrases[:9]
            more = (
                f" … (+{len(phrases) - len(shown)})"
                if len(phrases) > len(shown)
                else ""
            )
            out.append(
                f"- **{name.replace('_', ' ')}** — "
                + " · ".join(f"“{p}”" for p in shown)
                + more
            )
        out.append("")
    out += ["## Examples with arguments", "",
            "- “undo two moves”, “take over for five moves”, “save as blitz one”, “load blitz one”",
            "- “play at fifteen hundred”, “explain move twelve”, “read the last five moves”, “go to move five”",
            "- “what's on e four”, “what's attacking f seven”, “where's my queen”, “what can my knight do”",
            "", "## If I mishear you", "", NATO_LEGEND, ""]  # fmt: skip
    return "\n".join(out)


def build_keyboard() -> str:
    lines = [
        "# Jarvis Chess — keyboard (Classic Mode)",
        "",
        "| Key | Action |",
        "|---|---|",
    ]
    lines += [f"| `{k}` | {v} |" for k, v in SHORTCUTS]
    lines += [
        "",
        NOTE,
        "",
        "Mouse: click-to-move or drag; legal-move dots and capture rings; right-click a square to mark it, right-drag to draw an arrow; promotion pops out as a ring of four pieces.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    out = ROOT / "docs" / "chess"
    out.mkdir(parents=True, exist_ok=True)
    (out / "COMMANDS.md").write_text(build_commands())
    (out / "KEYBOARD.md").write_text(build_keyboard())
    print(f"wrote {out / 'COMMANDS.md'} and {out / 'KEYBOARD.md'}")


if __name__ == "__main__":
    main()
