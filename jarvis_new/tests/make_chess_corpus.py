def main() -> None:
    cases = []
    for pos, rows in ROWS.items():
        for text, exp in rows:
            cases.append(
                {"position": pos, "fen": POSITIONS[pos], "text": text, "expect": exp}
            )
    path = Path(__file__).with_name("voice_corpus.json")
    data = json.loads(path.read_text())
    data["chess_moves"] = cases
    path.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    print(len(cases), "chess rows written")


if __name__ == "__main__":
    main()
